const assert = require('node:assert/strict');
const { inventoryRows, stockLevel, stockValuation } = require(process.argv[2]);
const row = { productId:'a', total:9, available:5, assigned:3, disabled:1, availableKnownCostVnd:120000, availableKnownCostKeys:3 };
const rows = inventoryRows([row], [{id:'a'}, {id:'b'}]);
assert.equal(rows.length,2);
assert.deepEqual(rows[0],row);
assert.equal(rows[1].available,0);
assert.equal(rows[1].availableKnownCostKeys,0);
assert.equal(stockLevel(0,5),'empty');
assert.equal(stockLevel(1,5),'low');
assert.equal(stockLevel(5,5),'low');
assert.equal(stockLevel(6,5),'ok');
assert.deepEqual(stockValuation(row,50000),{knownKeys:3,knownCost:120000,unknownKeys:2,estimatedMargin:30000});
assert.equal(stockValuation(row,30000).estimatedMargin,-30000);
assert.equal(stockValuation(row).estimatedMargin,null);
assert.equal(stockValuation(rows[1],50000).estimatedMargin,null);
assert.equal(stockValuation({...row,availableKnownCostVnd:0},50000).estimatedMargin,150000);
assert.equal(stockValuation({productId:'legacy',total:2,available:2,assigned:0,disabled:0},50000).unknownKeys,2);
console.log('PASS: 14 inventory metrics assertions');
